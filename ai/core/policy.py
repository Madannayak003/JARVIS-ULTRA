"""
JARVIS ULTRA
AI Core - Model Policy

Defines which AI capabilities should prefer
which providers/models.

Policy decides preference.
Router decides availability and fallback.
"""

from typing import Dict, List


class AIModelPolicy:
    """
    Central model-selection policy.
    """

    # * ======================================================
    # * Provider Preference
    # * ======================================================

    PROVIDER_PREFERENCES: Dict[str, List[str]] = {

        # * --------------------------------------------------
        # * Coding
        # * --------------------------------------------------

        "coding": [
            "gemini",
        ],

        # * --------------------------------------------------
        # * Developer Mode
        # * --------------------------------------------------

        "developer": [
            "gemini",
        ],

        # * --------------------------------------------------
        # * Editing
        # * --------------------------------------------------

        "editing": [
            "gemini",
        ],

        # * --------------------------------------------------
        # * Repair
        # * --------------------------------------------------

        "repair": [
            "gemini",
        ],

        # * --------------------------------------------------
        # * Reasoning
        # * --------------------------------------------------

        "reasoning": [
            "gemini",
        ],

        # * --------------------------------------------------
        # * Conversation
        # * --------------------------------------------------

        "conversation": [
            "gemini",
        ],

        # * --------------------------------------------------
        # * Planning
        # * --------------------------------------------------

        "planning": [
            "gemini",
        ],

        # * --------------------------------------------------
        # * Memory
        # * --------------------------------------------------

        "memory": [
            "gemini",
        ],

        # * --------------------------------------------------
        # * Fast
        # * --------------------------------------------------

        "fast": [
            "gemini",
        ],

        # * --------------------------------------------------
        # * --------------------------------------------------
        # * Screen Vision
        # * --------------------------------------------------

        "screen_vision": [
            "gemini",
        ],
    }

    # * ======================================================
    # * Get Provider Preference
    # * ======================================================

    @classmethod
    def providers_for(
        cls,
        capability: str,
    ) -> List[str]:

        capability = (
            capability
            .strip()
            .lower()
        )

        return cls.PROVIDER_PREFERENCES.get(
            capability,
            [
                "gemini",
            ],
        )
